export interface Country { name: string; code: string }
export const COUNTRIES: Country[] = RAW.split("\n").map((l) => {
  const [name, code] = l.split("|");
  return { name, code };
});

/** يفصل رقماً كاملاً (أرقام فقط) إلى مفتاح + رقم محلي، بأطول مفتاح مطابق */
export function splitPhone(full: string): { cc: string; local: string } {
  const d = (full || "").replace(/\D/g, "");
  if (!d) return { cc: "966", local: "" };
  let best = "";
  for (const c of COUNTRIES) if (d.startsWith(c.code) && c.code.length > best.length) best = c.code;
  return best ? { cc: best, local: d.slice(best.length) } : { cc: "966", local: d };
}

/** يدمج المفتاح والرقم المحلي (يحذف الصفر الأول) */
export function joinPhone(cc: string, local: string): string {
  const l = (local || "").replace(/\D/g, "").replace(/^0+/, "");
  return l ? cc + l : "";
}
